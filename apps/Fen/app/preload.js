'use strict';
const { contextBridge, ipcRenderer, webUtils } = require('electron');
const call = async (ch, ...a) => { const r = await ipcRenderer.invoke(ch, ...a); if (!r.ok) throw new Error(r.error); return r.value; };
contextBridge.exposeInMainWorld('fen', {
  info: (p) => call('fen:info', p),
  display: (p) => call('fen:display', p),
  thumb: (p, size) => call('fen:thumb', p, size),
  siblings: (p) => call('fen:siblings', p),
  read: (p) => call('fen:read', p),
  exif: (p) => call('fen:exif', p),
  setOrientation: (p, o) => call('fen:setOrientation', p, o),
  write: (p, bytes) => call('fen:write', p, bytes),
  saveDialog: (def, filters) => call('fen:saveDialog', def, filters),
  confirm: (msg, detail, ok) => call('fen:confirm', msg, detail, ok),
  error: (msg, detail) => call('fen:error', msg, detail),
  askSave: (name) => call('fen:askSave', name),
  trash: (p) => call('fen:trash', p),
  reveal: (p) => call('fen:reveal', p),
  copyImage: (dataUrl) => call('fen:copyImage', dataUrl),
  wallpaper: (p) => call('fen:wallpaper', p),
  installFont: (p) => call('fen:installFont', p),
  fontInstalled: (p) => call('fen:fontInstalled', p),
  print: () => call('fen:print'),
  choose: () => call('fen:choose'),
  openFiles: (files) => call('fen:openFiles', files),
  signatures: { list: () => call('fen:sig:list'), add: (url) => call('fen:sig:add', url), remove: (id) => call('fen:sig:remove', id) },
  certs: { list: () => call('fen:certs:list'), choose: () => call('fen:certs:choose'), create: (v) => call('fen:certs:create', v) },
  sign: (req) => call('fen:sign', req),
  verify: (p) => call('fen:verify', p),
  me: () => call('fen:me'),
  pathFor: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  state: (s) => ipcRenderer.send('fen:state', s),
  fullscreen: (on) => ipcRenderer.send('fen:fullscreen', on),
  title: (t) => ipcRenderer.send('fen:title', t),
  onCommand: (fn) => ipcRenderer.on('fen:command', (_e, cmd, ...a) => fn(cmd, ...a)),
  onOpen: (fn) => ipcRenderer.on('fen:open', (_e, p) => fn(p)),
});
